#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# build.sh — builds the kiosk APK without gradle, from the SDK tools only.
#
# Deliberately without gradle and without dependencies: the app is a single
# Activity, so the whole build is aapt2 -> javac -> d8 -> zipalign -> apksigner.
# The whole thing can be read.
#
#   KIOSK_BASE_URL=https://<domain> ./build.sh            # builds build/signage-kiosk.apk
#   KIOSK_BASE_URL=https://<domain> ./build.sh install    # builds and installs via ADB
#
# The ADB target comes from the env: KIOSK_ADB=<ip>:5555 ./build.sh install
# Service address (the base, from which the allowed host is derived):
# KIOSK_BASE_URL=https://<domain>. There is no default: a build without it fails,
# so an APK can never be built against a wrong server by accident. It must be an
# https URL, otherwise the build fails.
# ---------------------------------------------------------------------------
set -euo pipefail

cd "$(dirname "$0")"

SDK=${ANDROID_HOME:-${ANDROID_SDK_ROOT:-$HOME/Android/Sdk}}
API=${API:-34}                       # what to compile against (targetSdk is in the manifest)
ANDROID_JAR="$SDK/platforms/android-$API/android.jar"
MIN_API=21

if [[ ! -f "$ANDROID_JAR" ]]; then
  echo "Not found: $ANDROID_JAR — set ANDROID_HOME or API=<version>." >&2
  exit 1
fi

BASE_URL=${KIOSK_BASE_URL:-}
if [[ -z "$BASE_URL" ]]; then
  echo "KIOSK_BASE_URL is not set (e.g. KIOSK_BASE_URL=https://example.com ./build.sh)." >&2
  exit 1
fi
BASE_URL=${BASE_URL%/}               # without a trailing slash (pairing URL = BASE_URL + "/connect")
if [[ ! "$BASE_URL" =~ ^https://[A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?(:[0-9]+)?(/[A-Za-z0-9._~/-]*)?$ ]]; then
  echo "KIOSK_BASE_URL must be an https URL (e.g. https://example.com), got: '$BASE_URL'" >&2
  exit 1
fi

for tool in aapt2 javac d8 zipalign apksigner keytool; do
  command -v "$tool" >/dev/null || { echo "Missing tool: $tool" >&2; exit 1; }
done

rm -rf build
mkdir -p build/classes build/dex build/gen/app/plainsignage/kiosk

# The service address reaches Java through a generated constant (build/gen).
cat > build/gen/app/plainsignage/kiosk/BaseUrl.java <<JAVA
package app.plainsignage.kiosk;

/** Generated by build.sh from KIOSK_BASE_URL. Do not edit. */
final class BaseUrl {
    static final String URL = "$BASE_URL";
    private BaseUrl() {}
}
JAVA
echo "Server: $BASE_URL"

echo "1/5  aapt2 — compile resources, pack the manifest, generate R.java"
aapt2 compile --dir res -o build/res.zip
aapt2 link \
  -I "$ANDROID_JAR" \
  --manifest AndroidManifest.xml \
  --min-sdk-version "$MIN_API" \
  --java build/gen \
  build/res.zip \
  -o build/base.apk

echo "2/5  javac — compile Java"
mapfile -d '' SOURCES < <(find src build/gen -name '*.java' -print0)
javac -nowarn -source 8 -target 8 \
  -bootclasspath "$ANDROID_JAR" -classpath "$ANDROID_JAR" \
  -d build/classes "${SOURCES[@]}"

echo "3/5  d8 — dex"
mapfile -d '' CLASSES < <(find build/classes -name '*.class' -print0)
d8 --lib "$ANDROID_JAR" --min-api "$MIN_API" \
  --output build/dex "${CLASSES[@]}"

echo "4/5  zip + zipalign"
( cd build/dex && zip -q ../base.apk classes.dex )
zipalign -f 4 build/base.apk build/aligned.apk

echo "5/5  sign"
# The signing key is generated locally on the first build and stays local
# (*.keystore and *.keystore.pass are in .gitignore). If it is lost, the next
# install over an existing app first requires an `adb uninstall` of the old app.
# Password: ${KIOSK_KS_PASS} if set; otherwise a random one is generated on the first
# build and stored next to the keystore in kiosk.keystore.pass (chmod 600).
PASS_FILE=kiosk.keystore.pass
if [[ -n "${KIOSK_KS_PASS:-}" ]]; then
  KS_PASS=$KIOSK_KS_PASS
elif [[ -f "$PASS_FILE" ]]; then
  KS_PASS=$(<"$PASS_FILE")
elif [[ -f kiosk.keystore ]]; then
  echo "kiosk.keystore exists but its password is unknown: set KIOSK_KS_PASS or create $PASS_FILE." >&2
  exit 1
else
  KS_PASS=$(head -c 24 /dev/urandom | base64 | tr -d '/+=\n')
  ( umask 077; printf '%s\n' "$KS_PASS" > "$PASS_FILE" )
fi
if [[ ! -f kiosk.keystore ]]; then
  echo "     (creating a new signing key kiosk.keystore)"
  keytool -genkeypair -keystore kiosk.keystore -storepass "$KS_PASS" \
    -keypass "$KS_PASS" -alias kiosk -keyalg RSA -keysize 2048 \
    -validity 10000 -dname "CN=Signage Kiosk" >/dev/null 2>&1
fi
export KS_PASS
apksigner sign --ks kiosk.keystore --ks-pass env:KS_PASS \
  --key-pass env:KS_PASS --out build/signage-kiosk.apk build/aligned.apk
rm -f build/base.apk build/aligned.apk build/signage-kiosk.apk.idsig

echo
apksigner verify --print-certs build/signage-kiosk.apk | head -2
ls -la build/signage-kiosk.apk

if [[ "${1:-}" == "install" ]]; then
  target=${KIOSK_ADB:-}
  [[ -n "$target" ]] || { echo "Set KIOSK_ADB=<ip>:5555" >&2; exit 1; }
  echo
  echo "Installing on $target …"
  adb connect "$target" >/dev/null || true
  adb -s "$target" install -r build/signage-kiosk.apk
fi
