    private static final int GOLD = 0xFFE3C47C;
    private static final int CREAM = 0xFFF5F0E4;
    private static final int GREY = 0xFF8F8A80;

    private TextView text(float size, int color, boolean bold) {
        TextView t = new TextView(this);
        t.setTextSize(android.util.TypedValue.COMPLEX_UNIT_DIP, size);
        t.setTextColor(color);
        t.setGravity(Gravity.CENTER);
        if (bold) {
            t.setTypeface(android.graphics.Typeface.DEFAULT_BOLD);
        }
        return t;
    }

    private void buildPrompt() {
        prompt = new FrameLayout(this);
        prompt.setBackgroundColor(0xF208080A);
        prompt.setClickable(true);            // a touch does not reach the player

        android.widget.LinearLayout column = new android.widget.LinearLayout(this);
        column.setOrientation(android.widget.LinearLayout.VERTICAL);
        column.setGravity(Gravity.CENTER_HORIZONTAL);

        TextView eyebrow = text(18, 0xFFC9A24D, false);
        eyebrow.setText(R.string.upd_eyebrow);
        eyebrow.setLetterSpacing(0.18f);
        promptTitle = text(44, CREAM, true);
        promptTitle.setPadding(0, 24, 0, 40);

        TextView ok = text(30, 0xFF08080A, true);
        ok.setText(R.string.upd_press_ok);
        android.graphics.drawable.GradientDrawable background =
                new android.graphics.drawable.GradientDrawable();
        background.setColor(GOLD);
        background.setCornerRadius(60);
        ok.setBackground(background);
        ok.setPadding(72, 28, 72, 28);

        TextView note = text(20, 0xFFC9C0AD, false);
        note.setText(R.string.upd_note);
        note.setPadding(0, 40, 0, 0);
        promptCountdown = text(16, GREY, false);
        promptCountdown.setPadding(0, 28, 0, 0);

        column.addView(eyebrow);
        column.addView(promptTitle);
        column.addView(ok, new android.widget.LinearLayout.LayoutParams(
                ViewGroup.LayoutParams.WRAP_CONTENT, ViewGroup.LayoutParams.WRAP_CONTENT));
        column.addView(note);
        column.addView(promptCountdown);
        // The column spans the full width: with WRAP_CONTENT it would be as narrow
        // as the button and longer texts would wrap and get clipped (verified on the stick).
        column.setPadding(80, 0, 80, 0);
        FrameLayout.LayoutParams lp = new FrameLayout.LayoutParams(
                ViewGroup.LayoutParams.MATCH_PARENT, ViewGroup.LayoutParams.WRAP_CONTENT);
        lp.gravity = Gravity.CENTER;
        prompt.addView(column, lp);
        prompt.setVisibility(View.GONE);
        root.addView(prompt, new FrameLayout.LayoutParams(
                ViewGroup.LayoutParams.MATCH_PARENT, ViewGroup.LayoutParams.MATCH_PARENT));
    }

    private void showPrompt(String version, long ms) {
        if (prompt == null) {
            buildPrompt();
        }
        promptTitle.setText(getString(R.string.upd_title,
                version == null || version.isEmpty() ? "" : version));
        promptUntil = SystemClock.elapsedRealtime() + ms;
        prompt.setVisibility(View.VISIBLE);
        prompt.bringToFront();
        if (countdown != null) {
            handler.removeCallbacks(countdown);
        }
        countdown = new Runnable() {
            @Override
            public void run() {
                long remaining = Math.max(0, promptUntil - SystemClock.elapsedRealtime()) / 1000;
                promptCountdown.setText(getString(R.string.upd_countdown,
                        String.format(java.util.Locale.ROOT, "%d:%02d", remaining / 60, remaining % 60)));
                if (prompt.getVisibility() == View.VISIBLE) {
                    handler.postDelayed(this, 1000);
                }
            }
        };
        countdown.run();
    }

    private void hidePrompt() {
        if (countdown != null) {
            handler.removeCallbacks(countdown);
        }
        if (prompt != null) {
            prompt.setVisibility(View.GONE);
        }
    }

    @Override
    protected void onDestroy() {
        if (updater != null) {
            updater.stop();
        }
        if (watchdogRunnable != null) {
            handler.removeCallbacks(watchdogRunnable);
        }
        if (networkCallback != null) {
            try {
                ((ConnectivityManager) getSystemService(Context.CONNECTIVITY_SERVICE))
                        .unregisterNetworkCallback(networkCallback);
            } catch (Exception ignored) {
                // the callback may have been unregistered already
            }
        }
        if (networkReceiver != null) {
            try {
                unregisterReceiver(networkReceiver);
            } catch (Exception ignored) {
                // the receiver may have been unregistered already
            }
        }
        super.onDestroy();
    }

    /**
     * An uncaught exception would leave the kiosk on a black screen. This way it
     * at least starts again — a deployed screen should heal itself,
     * not wait for a human.
     */
    private void installCrashHandler() {
        final Thread.UncaughtExceptionHandler previousHandler =
                Thread.getDefaultUncaughtExceptionHandler();
        Thread.setDefaultUncaughtExceptionHandler(new Thread.UncaughtExceptionHandler() {
            @Override
            public void uncaughtException(Thread t, Throwable e) {
                Log.e(TAG, "uncaught exception, restarting the kiosk", e);
                try {
                    Intent restart = new Intent(MainActivity.this, MainActivity.class);
                    restart.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK
                                 | Intent.FLAG_ACTIVITY_CLEAR_TASK);
                    // Crash-loop guard: at least 30 s between two starts.
                    // The time of the last (even scheduled) start is kept in prefs.
                    SharedPreferences p = getSharedPreferences(PREFS_FILE, MODE_PRIVATE);
                    long now = System.currentTimeMillis();
                    long last = p.getLong(PREF_KEY_LAST_RESTART, 0);
                    long next = Math.max(now, last + MIN_RESTART_GAP_MS);
                    if (last > now + MIN_RESTART_GAP_MS) {
                        next = now + MIN_RESTART_GAP_MS;   // the clock went backwards
                    }
                    p.edit().putLong(PREF_KEY_LAST_RESTART, next).commit();
                    if (next <= now) {
                        startActivity(restart);
                    } else {
                        Log.w(TAG, "crash within 30 s of the last restart, start postponed by "
                                + (next - now) + " ms");
                        int flags = PendingIntent.FLAG_UPDATE_CURRENT
                                | (android.os.Build.VERSION.SDK_INT >= 23
                                        ? PendingIntent.FLAG_IMMUTABLE : 0);
                        PendingIntent pi = PendingIntent.getActivity(
                                MainActivity.this, 0, restart, flags);
                        AlarmManager am = (AlarmManager) getSystemService(Context.ALARM_SERVICE);
                        if (am != null) {
                            am.set(AlarmManager.RTC_WAKEUP, next, pi);
                        }
                    }
                } catch (Exception ignored) {
                    // if even this fails, let the system deal with it
                }
                if (previousHandler != null) {
                    previousHandler.uncaughtException(t, e);
                } else {
                    android.os.Process.killProcess(android.os.Process.myPid());
                }
            }
        });
    }
